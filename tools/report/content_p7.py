def spot_hit(scene):
    """景区内可推荐景点的去重计数，口径与 search_spots 一致。"""
    names = set()
    for d in ENTS:
        if d.get('scenic_code') != scene:
            continue
        for m in d['mentions']:
            if m.get('poi_role') == 'attraction' and m.get('scope') == 'in_area':
                names.add(m.get('canonical_name') or m.get('text'))
    return len(names)


